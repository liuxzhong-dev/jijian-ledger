// 衣服码数选项。
//
// 为什么不能写死一个列表：制衣厂做的品类跨度极大——
//   内销女装：S M L XL XXL
//   外贸大码（欧美单）：XXXL XXXXL 5XL 6XL 8XL 10XL 12XL
//   童装：数字码 90 100 110 ... 170
//   还有些款做"均码"（one size）
// v1.0 只列了 S~XXL + 均，做外贸大码的厂直接没法记账
// （主人实际用出来的 bug：码数才到 XXL，更大码怎么办）。
//
// 所以分三层：
//   常用  —— 默认就显示，覆盖绝大多数内销厂，不占屏幕
//   更多  —— 点「更多码」才展开，大码和数字码都在这
//   自定义 —— 用户自己填（厂里怎么印就怎么填），并记住最近用的几个
//
// 码只是标签，不参与任何计算（金额 = 件数 × 单价），所以放开写不会影响算账。

class Sizes {
  /// 默认显示的常用码
  static const common = ['S', 'M', 'L', 'XL', 'XXL', '均码'];

  /// 展开后显示：欧美大码 + 童装/成人数字码
  static const more = [
    'XXXL', 'XXXXL', '5XL', '6XL', '8XL', '10XL', '12XL',
    '90', '100', '110', '120', '130', '140', '150', '160', '170',
  ];

  /// 全部内置码（自定义码不在这里，存在 settings 表）
  static const builtin = [...common, ...more];

  /// 记住几个自定义码。设上限是因为手机屏窄，太多反而难找
  static const maxCustom = 4;

  /// 单个码最长字符。菲票上偶尔会印 "XXXL(180)" 这种
  static const maxLen = 8;
}
